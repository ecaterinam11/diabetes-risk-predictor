"""Run every query in sql/03_analysis.sql and save the results as Markdown.

Usage (from the project root, after building the database):
    python src/run_analysis.py

Output: docs/analysis_results.md
"""

import numbers
import re
from pathlib import Path

import pandas as pd
from sqlalchemy import create_engine, text

ROOT = Path(__file__).resolve().parents[1]
DB_PATH = ROOT / "data" / "diabetes.db"
SQL_PATH = ROOT / "sql" / "03_analysis.sql"
OUT_PATH = ROOT / "docs" / "analysis_results.md"

HEADER = re.compile(r"^-- (Q\d+): (.+)$", re.MULTILINE)


def split_queries(sql: str) -> list[dict]:
    """Split the file on its '-- Qn: title' lines."""
    matches = list(HEADER.finditer(sql))
    queries = []
    for i, match in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(sql)
        body = sql[match.end():end].strip()
        note = re.search(r"^-- Technique: (.+)$", body, re.MULTILINE)
        queries.append({
            "id": match.group(1),
            "title": match.group(2),
            "technique": note.group(1) if note else "",
            "sql": body.rstrip(";"),
        })
    return queries


def to_markdown(df: pd.DataFrame) -> str:
    def fmt(value) -> str:
        if pd.isna(value):
            return ""
        if isinstance(value, float):
            return f"{value:,.0f}" if value.is_integer() and abs(value) >= 1000 else f"{value:g}"
        if isinstance(value, numbers.Integral):
            return f"{int(value):,}"
        return str(value)

    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(fmt(v) for v in row) + " |")
    return "\n".join(lines)


def main() -> None:
    if not DB_PATH.exists():
        raise SystemExit("Database not found. Run: python src/build_database.py")

    queries = split_queries(SQL_PATH.read_text(encoding="utf-8"))
    engine = create_engine(f"sqlite:///{DB_PATH.as_posix()}")

    parts = [
        "# Analysis results",
        "",
        "Generated by `python src/run_analysis.py` from [`sql/03_analysis.sql`](../sql/03_analysis.sql).",
        "Do not edit by hand.",
    ]
    with engine.connect() as conn:
        for q in queries:
            df = pd.read_sql(text(q["sql"]), conn)
            print(f"{q['id']}: {q['title']}  ({len(df)} rows)")
            parts += ["", f"## {q['id']}: {q['title']}", ""]
            if q["technique"]:
                parts += [f"*SQL technique: {q['technique']}*", ""]
            parts.append(to_markdown(df))
    engine.dispose()

    OUT_PATH.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"Saved {OUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
